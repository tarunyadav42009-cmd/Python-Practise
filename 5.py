dragon = [90, 45, 54, 72]

# 1. Get the sum using the built-in sum() function
total_sum = sum(dragon)
print(total_sum)  # Output: 261

# 2. Get the highest value using the built-in max() function
highest_value = max(dragon)
print(highest_value)  # Output: 90

# 3. The original list remains unchanged
print(dragon)  # Output: [90, 45, 54, 72]
